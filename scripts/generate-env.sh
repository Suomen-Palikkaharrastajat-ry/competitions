#!/usr/bin/env bash
set -euo pipefail

read -r -a PB_BIN <<< "${POCKETBASE:-pocketbase}"
PB_DATA_DIR="${PB_DATA_DIR:-./.devenv/state/pocketbase/data}"
ENV_FILE="${ENV_FILE:-.env}"
PB_PUBLIC_URL="${PB_PUBLIC_URL:-http://127.0.0.1:8080}"
PB_TEMP_PORT="${PB_TEMP_PORT:-18090}"
PB_API_KEY_DURATION_SECONDS="${PB_API_KEY_DURATION_SECONDS:-315360000}"
PB_SUPERUSER_EMAIL="${PB_SUPERUSER_EMAIL:-admin@example.test}"

if [ -z "${PB_SUPERUSER_PASSWORD:-}" ]; then
  PB_SUPERUSER_PASSWORD="$(openssl rand -base64 24 | tr -d '\n')"
fi

cleanup() {
  if [ -n "${PB_TEMP_PID:-}" ]; then
    kill "$PB_TEMP_PID" >/dev/null 2>&1 || true
    wait "$PB_TEMP_PID" >/dev/null 2>&1 || true
  fi
}
trap cleanup EXIT

json_field() {
  python3 -c 'import json,sys; value=json.load(sys.stdin)[sys.argv[1]]; print(json.dumps(value) if isinstance(value, (dict, list)) else value)' "$1"
}

wait_for_health() {
  local url="$1"
  local i
  for i in $(seq 1 30); do
    if curl -fsS "$url/api/health" >/dev/null 2>&1; then
      return 0
    fi
    sleep 0.5
  done
  return 1
}

start_temp_server() {
  mkdir -p .devenv/state/pocketbase
  "${PB_BIN[@]}" serve --automigrate=false --migrationsDir ./pb_migrations --hooksDir ./pb_hooks \
    --dir "$PB_DATA_DIR" \
    --http "127.0.0.1:$PB_TEMP_PORT" \
    --dev \
    > .devenv/state/pocketbase/generate-env.log 2>&1 &
  PB_TEMP_PID="$!"
  local url="http://127.0.0.1:$PB_TEMP_PORT"
  wait_for_health "$url"
  printf '%s\n' "$url"
}

find_server_url() {
  local candidates=()
  if [ -n "${PB_AUTH_URL:-}" ]; then
    candidates+=("$PB_AUTH_URL")
  fi
  candidates+=("http://127.0.0.1:8080" "http://127.0.0.1:8090")

  local url
  for url in "${candidates[@]}"; do
    if curl -fsS "$url/api/health" >/dev/null 2>&1; then
      printf '%s\n' "$url"
      return 0
    fi
  done

  start_temp_server
}

mkdir -p "$PB_DATA_DIR"
"${PB_BIN[@]}" migrate up --dir "$PB_DATA_DIR" --migrationsDir ./pb_migrations >/dev/null
"${PB_BIN[@]}" migrate up --dir "$PB_DATA_DIR" --migrationsDir ./pb_migrations_dev >/dev/null
"${PB_BIN[@]}" superuser upsert "$PB_SUPERUSER_EMAIL" "$PB_SUPERUSER_PASSWORD" --dir "$PB_DATA_DIR" >/dev/null

SERVER_URL="$(find_server_url)"

AUTH_PAYLOAD="$(
  PB_SUPERUSER_EMAIL="$PB_SUPERUSER_EMAIL" \
  PB_SUPERUSER_PASSWORD="$PB_SUPERUSER_PASSWORD" \
  python3 - <<'PY'
import json
import os

print(json.dumps({
    "identity": os.environ["PB_SUPERUSER_EMAIL"],
    "password": os.environ["PB_SUPERUSER_PASSWORD"],
}))
PY
)"

AUTH_RESPONSE="$(
  curl -fsS \
    -H 'Content-Type: application/json' \
    -X POST \
    "$SERVER_URL/api/collections/_superusers/auth-with-password" \
    -d "$AUTH_PAYLOAD"
)"

SUPERUSER_ID="$(printf '%s' "$AUTH_RESPONSE" | json_field 'record' | json_field 'id')"
LOGIN_TOKEN="$(printf '%s' "$AUTH_RESPONSE" | json_field 'token')"

API_KEY_RESPONSE="$(
  curl -fsS \
    -H "Authorization: Bearer $LOGIN_TOKEN" \
    -H 'Content-Type: application/json' \
    -X POST \
    "$SERVER_URL/api/collections/_superusers/impersonate/$SUPERUSER_ID" \
    -d "{\"duration\":$PB_API_KEY_DURATION_SECONDS}"
)"

POCKETBASE_API_KEY="$(printf '%s' "$API_KEY_RESPONSE" | json_field 'token')"

VERIFY_CODE="$(
  curl -sS -o /dev/null -w '%{http_code}' \
    -H "Authorization: Bearer $POCKETBASE_API_KEY" \
    "$SERVER_URL/api/collections/profiles/records?perPage=1"
)"

if [ "$VERIFY_CODE" != "200" ]; then
  echo "Generated token failed verification against $SERVER_URL (HTTP $VERIFY_CODE)" >&2
  exit 1
fi

TMP_ENV="$(mktemp)"
cat > "$TMP_ENV" <<EOF
# Generated by make .env.
# Local development only. Do not commit real production secrets.

POCKETBASE_URL=$PB_PUBLIC_URL
POCKETBASE_API_KEY=$POCKETBASE_API_KEY

# Local PocketBase superuser used to mint the API key above.
PB_SUPERUSER_EMAIL=$PB_SUPERUSER_EMAIL
PB_SUPERUSER_PASSWORD=$PB_SUPERUSER_PASSWORD

# Elm/Vite talks to PocketBase through Caddy in local development.
VITE_POCKETBASE_URL=$PB_PUBLIC_URL
EOF

mv "$TMP_ENV" "$ENV_FILE"
chmod 600 "$ENV_FILE"

echo "Wrote $ENV_FILE with a verified PocketBase API key for $PB_PUBLIC_URL"
